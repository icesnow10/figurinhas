function gerarFigurinhasSelecao(): Sticker[] {
  const list: Sticker[] = [];
  SELECOES.forEach((sel) => {
    for (let i = 1; i <= 20; i++) {
      const numero = i;
      const pos = POSICOES_TIME[i - 1];
      let nome = '';
      let raridade: Sticker['raridade'] = 'comum';

      const codigo = `${sel.id}${String(numero).padStart(2, '0')}`;
      if (pos === 'ESC') {
        nome = `Escudo - ${sel.nome}`;
        raridade = 'especial';
      } else if (pos === 'TIME') {
        nome = `Time perfilado - ${sel.nome}`;
        raridade = 'rara';
      } else if (NOMES_JOGADORES[codigo]) {
        nome = `${NOMES_JOGADORES[codigo]} - ${sel.nome}`;
      } else {
        const numJogador = i < 13 ? i - 1 : i - 2;
        nome = `Jogador ${numJogador} - ${sel.nome}`;
      }

      const imagemReal = IMAGENS_REAIS[codigo];
      const imagem = imagemReal
        ? imagemReal.replace(/\/([^/]+)\.(jpe?g|png|webp)$/i, '/thumbs/$1.webp')
        : placeholderImage(`${sel.id} ${numero}`, sel.cor.replace('#', ''), 'FFFFFF');
      list.push({
        id: codigo,
        codigo,
        numero,
        nome,
        imagem,
        raridade,
        tipo: 'selecao',
        selecaoId: sel.id,
        posicao: pos,
        ...(numero === 13 ? { rotation: 90 } : {}),
      });
    }
  });
  return list;
}

function gerarEspeciais(): Sticker[] {
  const list: Sticker[] = [];

  const rotationFor = (codigo: string): number | undefined => {
    if (codigo === '00') return 90;
    if (codigo === 'FWC4') return undefined;
    if (codigo === 'FWC5') return undefined;
    const m = codigo.match(/^FWC(\d+)$/);
    if (m) {
      const n = Number(m[1]);
      if ((n >= 1 && n <= 3) || (n >= 9 && n <= 19)) return 90;
    }
    return undefined;
  };

  {
    const codigo = '00';
    const imagemReal = IMAGENS_REAIS[codigo];
    const rot = rotationFor(codigo);
    list.push({
      id: codigo,
      codigo,
      numero: 0,
      nome: 'Logo Oficial',
      imagem: imagemReal
        ? imagemReal.replace(/\/([^/]+)\.(jpe?g|png|webp)$/i, '/thumbs/$1.webp')
        : placeholderImage(codigo, 'C0C0C0', '000000'),
      raridade: 'especial',
      tipo: 'especial',
      selecaoId: 'INTRO',
      ...(rot !== undefined ? { rotation: rot } : {}),
    });
  }

  NOMES_INTRO.forEach((nome, idx) => {
    const numero = idx + 1;
    const codigo = `FWC${numero}`;
    const imagemReal = IMAGENS_REAIS[codigo];
    const rot = rotationFor(codigo);
    const isFWC5 = codigo === 'FWC5';
    list.push({
      id: codigo,
      codigo,
      numero,
      nome,
      imagem: imagemReal
        ? imagemReal.replace(/\/([^/]+)\.(jpe?g|png|webp)$/i, '/thumbs/$1.webp')
        : placeholderImage(codigo, 'FFD700', '000000'),
      raridade: 'especial',
      tipo: 'especial',
      selecaoId: 'INTRO',
      ...(rot !== undefined ? { rotation: rot } : {}),
      ...(isFWC5 ? { spanCols: 2, spanRows: 2 } : {}),
    });
  });

  NOMES_MUSEU.forEach((nome, idx) => {
    const numero = idx + 9;
    const codigo = `FWC${numero}`;
    const imagemReal = IMAGENS_REAIS[codigo];
    const rot = rotationFor(codigo);
    list.push({
      id: codigo,
      codigo,
      numero,
      nome,
      imagem: imagemReal
        ? imagemReal.replace(/\/([^/]+)\.(jpe?g|png|webp)$/i, '/thumbs/$1.webp')
        : placeholderImage(codigo, 'C9A961', '000000'),
      raridade: 'legend',
      tipo: 'especial',
      selecaoId: 'MUSEU',
      ...(rot !== undefined ? { rotation: rot } : {}),
    });
  });

  NOMES_COCA_COLA.forEach((nome, idx) => {
    const numero = idx + 1;
    const codigo = `CC${String(numero).padStart(2, '0')}`;
    list.push({
      id: codigo,
      codigo,
      numero,
      nome,
      imagem: placeholderImage(codigo, 'E41E2B', 'FFFFFF'),
      raridade: 'especial',
      tipo: 'especial',
      selecaoId: 'COCA',
    });
  });

  MCDONALDS_PAISES.forEach(({ paisId, nome }) => {
    const codigo = `MCD${paisId}13`;
    const imagemMcd = IMAGENS_REAIS[codigo];
    const imagemRegular = IMAGENS_REAIS[`${paisId}13`];
    const fonte = imagemMcd ?? imagemRegular;
    list.push({
      id: codigo,
      codigo,
      numero: 13,
      nome: `McDonald's - ${nome} #13`,
      imagem: fonte
        ? fonte.replace(/\/([^/]+)\.(jpe?g|png|webp)$/i, '/thumbs/$1.webp')
        : placeholderImage(`${paisId} 13 MCD`, 'FFC72C', 'C8102E'),
      raridade: 'especial',
      tipo: 'especial',
      selecaoId: 'MCD',
      slotDeId: `${paisId}13`,
      rotation: 90,
    });
  });

  return list;
}

export function idsAlternativosDoSlot(stickerId: string): string[] {
  const mcdMatch = stickerId.match(/^MCD([A-Z]{3})13$/);
  if (mcdMatch) return [`${mcdMatch[1]}13`, stickerId];
  const regMatch = stickerId.match(/^([A-Z]{3})13$/);
  if (regMatch && MCDONALDS_PAISES_IDS.includes(regMatch[1])) {
    return [stickerId, `MCD${regMatch[1]}13`];
  }
  return [stickerId];
}

export function temVersaoMcDonalds(stickerId: string): boolean {
  const m = stickerId.match(/^([A-Z]{3})13$/);
  if (!m) return false;
  return MCDONALDS_PAISES_IDS.includes(m[1]);
}

export function obterIdMcDonalds(stickerOriginalId: string): string | null {
  const m = stickerOriginalId.match(/^([A-Z]{3})13$/);
  if (!m) return null;
  if (!MCDONALDS_PAISES_IDS.includes(m[1])) return null;
  return `MCD${m[1]}13`;
}

