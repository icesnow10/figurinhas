function escaparTexto(s: string) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function placeholderImage(label: string, bg = '0A2540', fg = 'FFFFFF'): string {
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 280" preserveAspectRatio="xMidYMid slice">` +
    `<rect width="200" height="280" fill="#${bg}"/>` +
    `<text x="100" y="150" text-anchor="middle" dominant-baseline="middle" font-family="Montserrat,Arial,sans-serif" font-weight="700" font-size="28" fill="#${fg}">${escaparTexto(label)}</text>` +
    `</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

